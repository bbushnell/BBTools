package test.kmer;

import java.util.ArrayList;
import java.util.Arrays;

import kmer.AbstractKmerTable;
import kmer.AbstractKmerTableSet;
import kmer.HashArray1D;
import kmer.KmerTableSet;
import kmer.ScheduleMaker;
import shared.Shared;

/** Checks requested, default and preallocated TableSet capacities without loading reads.
 * Run one case per fresh JVM with -Xms256m -Xmx256m under either assertion mode.
 * Planner guards bound real allocations before calling the production allocator;
 * full preallocation is checked on planner metadata only.
 * @author Sucrose
 */
public final class KmerTableSetAllocationTest{

	/** Runs one finite allocation contract; manual checks remain active with -da. */
	public static void main(String[] args){
		if(args.length!=1 || !args[0].startsWith("case=")){
			throw new IllegalArgumentException("Expected case=requested|default-control|prealloc-control.");
		}
		final String mode=args[0].substring(5);
		if(!mode.equals("requested") && !mode.equals("default-control") && !mode.equals("prealloc-control")){
			throw new IllegalArgumentException("Unknown allocation case: "+mode);
		}
		final long maxHeap=Runtime.getRuntime().maxMemory();
		final double xmsRatio=Shared.xmsRatio();
		check(maxHeap>=240L*1024*1024 && maxHeap<=256L*1024*1024 && xmsRatio>0.97, mode,
			"Fixture needs -Xms256m -Xmx256m with effective heap 240..256 MiB: maxHeap="+maxHeap+", xmsRatio="+xmsRatio);
		Shared.setThreads(1);
		Shared.AMINO_IN=false;
		AbstractKmerTableSet.MASK_CORE=false;
		AbstractKmerTableSet.MASK_MIDDLE=false;
		AbstractKmerTableSet.DISPLAY_PROGRESS=false;
		check(new HashArray1D(new int[] {17}, -1L).arrayLength()==77,
			mode, "Literal capacity oracles require the actual 60-cell probe tail");
		final ScheduleMaker defaults=new ScheduleMaker(1, 12, false, 1, -1);
		final int defaultFirst=defaults.makeSchedule()[0];
		check(defaultFirst>37 && defaultFirst<400000 && defaults.maxSize>2*128000,
			mode, "Fixture requires a bounded default allocation and room for the requested-size ladder: "+defaults);
		final ScheduleMaker fractional=new ScheduleMaker(1, 12, true, 0.001, -1);
		final int[] fractionSchedule=fractional.makeSchedule();
		check(fractionSchedule.length==1 && fractionSchedule[0]==fractional.maxSize
			&& fractional.maxSize>37 && fractional.maxSize<20000,
			mode, "Fixture fractional preallocation must be one bounded maximum: "+fractional);

		if(mode.equals("requested")){
			final int primary=allocate("17", "f", mode);
			//The last unappended integer is at most33; prime rounding can raise it to37.
			//The oracle is literal, not generated by a second requested-size planner.
			check(primary>=17 && primary<=37, mode,
				"Requested initialsize17 must produce 17..37 primary cells; actual="+primary);
		}else if(mode.equals("default-control")){
			final int omitted=allocate(null, "f", mode);
			final int zero=allocate("0", "f", mode);
			final int negative=allocate("-1", "f", mode);
			check(omitted==defaultFirst && zero==omitted && negative==omitted, mode,
				"Omitted, zero and negative initialsize must retain the default allocation: "+
				omitted+", "+zero+", "+negative+"; expected="+defaultFirst);
		}else{
			final int omitted=allocate(null, "0.001", mode);
			final int requested=allocate("17", "0.001", mode);
			check(omitted==fractional.maxSize && requested==omitted, mode,
				"Fractional preallocation must ignore the lower bound and allocate its maximum: "+
				omitted+", "+requested+"; expected="+fractional.maxSize);
			final ScheduleMaker fullDefault=new ScheduleMaker(1, 12, true, 1, -1);
			final ScheduleMaker fullRequested=new ScheduleMaker(1, 12, true, 1, 17);
			final int[] a=fullDefault.makeSchedule(), b=fullRequested.makeSchedule();
			check(a.length==1 && b.length==1 && a[0]==fullDefault.maxSize
				&& b[0]==fullRequested.maxSize && Arrays.equals(a, b), mode,
				"Full preallocation must ignore the lower bound; no full-budget arrays are needed");
		}
		System.out.println("PASS tableset-allocation case="+mode);
	}

	/** Allocates exactly one empty real shard with no input, prefilter or load operation.
	 * Null initial omits the flag; nonnull values are passed verbatim to the parser.
	 * @return Actual primary capacity, excluding the separately checked probe tail
	 */
	private static int allocate(final String initial, final String prealloc, final String mode){
		final ArrayList<String> args=new ArrayList<String>(Arrays.asList(
			"k=3", "ways=1", "threads=1", "prefilter=0", "onepass=f", "prealloc="+prealloc));
		if(initial!=null){args.add("initialsize="+initial);}
		final KmerTableSet set=new KmerTableSet(args.toArray(new String[args.size()]), 12);
		check(Shared.threads()==1 && set.ways==1 && set.k==3 && !set.amino
			&& !set.prefilter && !set.onePass && set.tables()==null && set.prefilterArray==null
			&& set.in1.isEmpty() && set.in2.isEmpty() && set.extra.isEmpty(), mode,
			"Fixture requires one unallocated DNA shard with no inputs or prefilter");
		if("17".equals(initial)){
			check(set.initialSize==17, mode, "The requested initialsize must reach the parsed field before allocation");
		}
		set.allocateTables();
		final AbstractKmerTable[] tables=set.tables();
		check(tables!=null && tables.length==1 && tables[0] instanceof HashArray1D,
			mode, "Production allocation must return one HashArray1D shard");
		final AbstractKmerTable table=tables[0];
		check(table.size()==0 && table.getValue(0)==-1 && !set.errorState
			&& set.prefilterArray==null && set.readsIn==0 && set.basesIn==0 && set.kmersIn==0,
			mode, "Allocation must leave an empty table without loading data or reporting an error");
		final int primary=table.arrayLength()-60;
		set.clear();
		return primary;
	}

	/** Makes both fixture preconditions and contract failures visible with assertions disabled. */
	private static void check(final boolean ok, final String mode, final String message){
		if(!ok){throw new AssertionError("KMR024 case="+mode+": "+message);}
	}
}
