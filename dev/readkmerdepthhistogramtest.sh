#!/usr/bin/env bash
# Run one depth-histogram regression case in a fresh JVM; no compilation.
set -eo pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
. "$DIR/javasetup.sh"
parseJavaArgs --xmx=256m --xms=256m --mode=fixed simd=f eoom "$@"
setEnvironment
exec java -Dfile.encoding=UTF-8 -XX:ActiveProcessorCount=1 $EA $EOOM $SIMD $XMX $XMS -cp "$DIR/current/" test.jgi.ReadKmerDepthHistogramTest "$@"
